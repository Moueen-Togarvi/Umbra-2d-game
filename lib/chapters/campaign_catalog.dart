  static String roman(int value) {
    var n = value;
    final out = StringBuffer();
    for (final entry in const [
      (40, 'XL'),
      (10, 'X'),
      (9, 'IX'),
      (5, 'V'),
      (4, 'IV'),
      (1, 'I'),
    ]) {
      while (n >= entry.$1) {
        out.write(entry.$2);
        n -= entry.$1;
      }
    }
    return out.toString();
  }
